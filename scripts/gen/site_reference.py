#!/usr/bin/env python3
"""Write the website's reference pages from the documents they show (decision B18).

The reference section of the site (site/content/reference/) used to be hand copies of documents
under docs/, and every one of them had drifted from its source, some by hundreds of lines. A copy
that can drift is a second owner of the same text. The pages are now generated at build time from
PAGES below, like the specification pages (scripts/spec/spec.py site), and are not tracked: the
book workflow and `make docs-site` run this before zola, and check_site_generated.sh refuses a
tracked copy.

  site_reference.py --out site/content/reference     write the pages (and remove stale ones)
  site_reference.py --list                           print page -> source
"""
import argparse, glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REPO_URL = "https://github.com/unbalancedparentheses/concrete2/blob/main/"

# page file -> (title, source document). The page names are the stable URLs other pages link to.
PAGES = {
    "ABI.md": ("ABI", "docs/platform/ABI.md"),
    "ARCHITECTURE.md": ("Architecture", "docs/compiler/ARCHITECTURE.md"),
    "DIAGNOSTICS.md": ("Diagnostics", "docs/compiler/DIAGNOSTICS.md"),
    "EXECUTION_MODEL.md": ("Execution Model", "docs/platform/EXECUTION_MODEL.md"),
    "FFI.md": ("FFI", "docs/platform/FFI.md"),
    "PASSES.md": ("Compiler Pass Contracts", "docs/compiler/PASSES.md"),
    "PROJECT.md": ("Project", "docs/project/PROJECT.md"),
    "PROVABLE_SUBSET.md": ("Provable Subset", "docs/verification/PROVABLE_SUBSET.md"),
    "SAFETY.md": ("Safety", "docs/language/SAFETY.md"),
    "STDLIB.md": ("Stdlib", "docs/stdlib/STDLIB.md"),
    "TESTING.md": ("Testing", "docs/compiler/TESTING.md"),
    "VALUE_MODEL.md": ("Value Model", "docs/language/VALUE_MODEL.md"),
}
# Old page URLs kept alive as Zola redirects to the page that absorbed them (page -> URL paths).
# docs/project's IDENTITY, DESIGN_POLICY, LANGUAGE_SHAPE and DECISIONS became PROJECT.md on
# 2026-10-29; their published reference pages redirect there so outside links do not break.
ALIASES = {
    "PROJECT.md": ["/reference/identity/", "/reference/design-policy/",
                   "/reference/language-shape/", "/reference/decisions/"],
}
INDEX = '''+++
title = "Index"
description = "Stable contracts for the language model, compiler, safety rules, ABI, diagnostics, testing, and stdlib direction."
+++

<!-- GENERATED by scripts/gen/site_reference.py -- do not edit -->
Concrete's reference documents, generated from the repository at build time. The language rules
themselves are the [language specification](@/spec/_index.md); where a document below restates
one, the specification is authoritative.
'''
MARK = "<!-- GENERATED from {src} by scripts/gen/site_reference.py -- do not edit -->"
LINK = re.compile(r"\[([^\]]*)\]\(([^)#\s]*)(#[^)\s]*)?\)")

def rewrite(txt, src):
    by_src = {s: p for p, (_, s) in PAGES.items()}
    here = os.path.dirname(src)
    def sub(m):
        text, tgt, frag = m.group(1), m.group(2), m.group(3) or ""
        if not tgt or re.match(r"[a-z]+:", tgt) or tgt.startswith("@"): return m.group(0)
        path = os.path.normpath(os.path.join(here, tgt))
        if path in by_src: return f"[{text}](@/reference/{by_src[path]}{frag})"
        m2 = re.fullmatch(r"docs/spec/([a-z]+)\.md", path)
        if m2 and m2.group(1) != "README": return f"[{text}](@/spec/{m2.group(1)}.md{frag})"
        return f"[{text}]({REPO_URL}{path}{frag})"
    return LINK.sub(sub, txt)

def aliases(page):
    paths = ALIASES.get(page)
    return "aliases = [" + ", ".join(f'"{p}"' for p in paths) + "]\n" if paths else ""

def generate(out):
    os.makedirs(out, exist_ok=True)
    for f in glob.glob(os.path.join(out, "*.md")): os.remove(f)
    open(os.path.join(out, "_index.md"), "w", encoding="utf-8").write(INDEX)
    for page, (title, src) in PAGES.items():
        txt = open(os.path.join(ROOT, src), encoding="utf-8").read()
        open(os.path.join(out, page), "w", encoding="utf-8").write(
            f'+++\ntitle = "{title}"\n{aliases(page)}+++\n\n{MARK.format(src=src)}\n{rewrite(txt, src)}')
    return len(PAGES)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    if a.list:
        for p, (_, s) in PAGES.items(): print(f"{p}\t{s}")
        return 0
    if not a.out: ap.error("--out or --list")
    missing = [s for _, s in PAGES.values() if not os.path.exists(os.path.join(ROOT, s))]
    if missing: print("site_reference: missing sources: " + ", ".join(missing), file=sys.stderr); return 1
    print(f"site_reference: wrote {generate(a.out)} pages to {a.out}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
