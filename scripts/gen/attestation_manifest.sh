#!/usr/bin/env bash
# Attestation manifest: which SUBJECT each evidence-bearing proof table is attested to.
#
# THIS SCRIPT IS ORCHESTRATION, NOT AN IDENTITY PRODUCER — and that distinction is the whole design.
# An earlier version derived package identity from directory layout in shell. That would have made it
# a SECOND producer of implementation identity, reintroducing two answers at the exact moment R-0004
# exists to eliminate them, and it answered a different question from the one the `ProofCore`
# boundary already answers.
#
# So identity comes from `--report attestation-join`, which the compiler emits from the same facts it
# uses at that boundary. This script only JOINS those rows against the table inventory.
#
# PACKAGE SCOPE COMES FROM THE CONSUMING SUBJECT, never from a theorem's filesystem location. An
# in-repo theorem needs no package of its own: the attestation target is the implementation subject
# consuming that theorem and table, and every subject has a package because the boundary requires one.
#
# DENOMINATORS ARE TYPED. Every input row ends mapped, explicitly excluded, or refused — so "31 vs 43"
# becomes a reconciliation rather than two counters that happen to differ.
set -uo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$ROOT_DIR/scripts/tests/lib/has_match.sh" || exit 2  # bug 283: never a pipe into grep -q
cd "$ROOT_DIR"
BIN=".lake/build/bin/concrete"
[ -x "$BIN" ] || { echo "FATAL: build first (missing $BIN)" >&2; exit 1; }

REFUSALS=0
refuse() { echo "REFUSE: $1" >&2; REFUSALS=$((REFUSALS+1)); }

# --- drift fixtures: CLASSIFIED by their own header, not by filename -----------------------------
# A renamed drift fixture stays classified; an innocent `*_drifted` name is not misclassified.
DRIFT="$(grep -rlE '^// .*DRIFTED variant' examples --include='*.con' 2>/dev/null | sort)"

# --- the compiler's join rows, per fixture ------------------------------------------------------
# One row per claiming subject: identity, package, module, decl, implementation, theorem, tables.
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
: > "$TMP/rows.tsv"
: > "$TMP/deprows.tsv"
: > "$TMP/scopes.tsv"
SUBJECTS=0; NOID=0; SCANNED=0; EXCLUDED=0
while IFS= read -r con; do
  SCANNED=$((SCANNED+1))
  isdrift=no
  for d in $DRIFT; do [ "$con" = "$d" ] && isdrift=yes; done
  if [ "$isdrift" = yes ]; then EXCLUDED=$((EXCLUDED+1)); continue; fi
  while IFS= read -r line; do
    case "$line" in \#*|"") continue ;; esac
    # ROLE-SPLIT AT THE DOOR. The report carries two populations and the subject accounting is
    # FROZEN at 86/48, so a dependency row must never reach the subject counters — that is the whole
    # reason the role column exists, and inferring the population from a row's shape is what it
    # exists to prevent.
    case "$line" in
      dependency*)
        printf '%s\t%s\n' "$line" "$con" >> "$TMP/deprows.tsv"
        continue ;;
    esac
    printf '%s\t%s\n' "$line" "$con" >> "$TMP/rows.tsv"
    SUBJECTS=$((SUBJECTS+1))
    case "$line" in *"NO-IDENTITY"*) NOID=$((NOID+1)) ;; esac
  done < <("$BIN" "$con" --report attestation-join 2>/dev/null || true)
  # The fixture's scope, origin and artifact, for the D1 check below (R-0482).
  "$BIN" "$con" --report package-identity 2>/dev/null \
    | awk -F'\t' -v c="$con" '$1 == "scope" {s = $2 "\t" $3 "\t" $4} $1 == "artifact" {a = $2}
                              END {if (s != "") print c "\t" s "\t" a}' >> "$TMP/scopes.tsv"
done < <(grep -rlE '#\[(proof_by|ensures_proof)\(' examples --include='*.con' 2>/dev/null | sort)

# D1 AT THE ATTESTATION SURFACE (R-0482). Two fixtures that are DIFFERENT packages (different
# artifacts) under one undeclared name have one scope digest by construction — `undeclared` plus a
# name is the whole scope — so their attestations would key as one package's. Refused, naming both;
# declaring an `origin` in either [package] section resolves it.
if [ -s "$TMP/scopes.tsv" ]; then
  while IFS=$'\t' read -r name fixtures; do
    refuse "two different packages named '$name' declare no origin, so they share one scope: $fixtures — declare \`origin\` in one [package] section"
  done < <(awk -F'\t' '$4 == "undeclared" {
             k = $2; if (!(k in art)) {art[k] = $5; who[k] = $1; nm[k] = $3}
             else if (art[k] != $5) {bad[k] = 1; who[k] = who[k] " " $1} }
           END {for (k in bad) print nm[k] "\t" who[k]}' "$TMP/scopes.tsv" | sort)
fi

# TEST SEAM, unset in normal use. `scripts/tools/identity_rows.sh` freezes the COMPILER's rows for the
# R-0482 migration; reading them here keeps one enumeration of the corpus instead of a second copy of
# the fixture scan and drift classifier that could disagree with this one.
if [ -n "${ATTESTATION_JOIN_ROWS_OUT:-}" ]; then
  cat "$TMP/rows.tsv" "$TMP/deprows.tsv" > "$ATTESTATION_JOIN_ROWS_OUT"
fi

echo "# GENERATED by scripts/gen/attestation_manifest.sh. Do not edit."
echo "# Identity is produced by the COMPILER (--report attestation-join); this joins, it does not derive."
echo
echo "[drift-exclusions]"
for d in $DRIFT; do echo "excluded = \"$d\"  # declares itself a DRIFTED variant"; done
echo

# --- the mapping: table -> attested subject ------------------------------------------------------
echo "[table-attestations]"
MAPPED=0; UNTABLED=0
: > "$TMP/pairs.tsv"
while IFS=$'\t' read -r _tag ident pkg mod decl impl thm tables src; do
  [ "$ident" = "NO-IDENTITY" ] && continue
  if [ "$tables" = "-" ] || [ -z "$tables" ]; then UNTABLED=$((UNTABLED+1)); continue; fi
  IFS=',' read -ra TS <<< "$tables"
  for t in "${TS[@]}"; do
    echo "$t <- $pkg/$mod.$decl impl=$impl  # via $thm ($src)"
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$t" "$pkg" "$mod" "$decl" "$impl" "$src" >> "$TMP/pairs.tsv"
    MAPPED=$((MAPPED+1))
  done
done < "$TMP/rows.tsv"
echo

# --- dependency attestations: one exact implementation per requested body-edge callee ------------
#
# THE POPULATION CORRESPONDENCE ACTUALLY JOINS OVER. A subject row exists because a fixture links a
# proof to a declaration; a body edge exists because that declaration CALLS another one. Those are
# different sets, and the difference was invisible while the join matched on `CallableId`: a callee
# with no proof link of its own matched on NAME and reported `usable=yes`, with nothing to attest a
# table entry to.
#
# THE SUBJECT SECTION ABOVE IS BYTE-STABLE AND STRICTLY SUBJECT-ONLY. `table_attestations` stays 48.
# The `binding_role` field lives in the compiler report for BOTH populations; it is written into the
# manifest only here, because adding it to the subject lines would change the frozen output.
#
# A DEPENDENCY ATTESTATION IS AN IDENTITY, NOT A JUSTIFICATION. It states which implementation an
# edge points at. It is not proof linkage, not model faithfulness, and not root availability — an
# unlinked helper with an exact reference still has no usable proof node.
#
# THE KEY IS (consumer, table, callee), produced by the compiler. Keyed by (fixture, callee) instead,
# `proof_pressure.check_nonce` would look satisfied by its `cryptoFns` row while the theorem claiming
# `validate_header` requests `elfFns` — the exact misattachment this work exists to keep visible.
#
# EVERY REQUEST IS EMITTED, whatever its disposition, and the whole population is emitted rather than
# the subset lacking a subject row: a callee gaining a proof link must not make its dependency
# request disappear, or the denominator shrinks when the corpus improves.
DEPREQ=0; DEPATT=0; DEPREF=0; DEPNOID=0; DEPVC=0; DEPVG=0; DEPUN=0
: > "$TMP/deppairs.tsv"
: > "$TMP/depatt.txt"
: > "$TMP/depref.txt"
while IFS= read -r line; do
  [ -n "$line" ] || continue
  src="$(printf '%s' "$line" | awk -F'\t' '{print $NF}')"
  consumer="$(printf '%s' "$line" | awk -F'\t' '{print $3}')"
  cname="$(printf '%s' "$line" | awk -F'\t' '{print $4}')"
  tbl="$(printf '%s' "$line" | awk -F'\t' '{print $5}')"
  disp="$(printf '%s' "$line" | awk -F'\t' '{print $6}')"
  kind="$(printf '%s' "$line" | awk -F'\t' '{print $7}')"
  ident="$(printf '%s' "$line" | awk -F'\t' '{print $8}')"
  pkg="$(printf '%s' "$line" | awk -F'\t' '{print $9}')"
  mod="$(printf '%s' "$line" | awk -F'\t' '{print $10}')"
  decl="$(printf '%s' "$line" | awk -F'\t' '{print $11}')"
  impl="$(printf '%s' "$line" | awk -F'\t' '{print $12}')"
  DEPREQ=$((DEPREQ+1))
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$consumer" "$tbl" "$pkg" "$mod" "$decl" "$impl" >> "$TMP/deppairs.tsv"
  if [ "$ident" = "NO-IDENTITY" ]; then
    DEPNOID=$((DEPNOID+1)); DEPREF=$((DEPREF+1))
    echo "$tbl !! $mod.$decl  binding_role=dependency  refusal=$kind  # requested by $cname ($src)" >> "$TMP/depref.txt"
  elif [ "$disp" = "refused" ]; then
    DEPREF=$((DEPREF+1))
    echo "$tbl !! $pkg/$mod.$decl  binding_role=dependency  refusal=$kind  # requested by $cname [$consumer] ($src)" >> "$TMP/depref.txt"
  else
    DEPATT=$((DEPATT+1))
    # MODEL-PRESENCE PROVENANCE IS CARRIED THROUGH, never summarised away — and it is MODEL presence,
    # not scoped membership. `present:compiler-linked` was checked against a table the compiler holds
    # and whose body digests it recomputed; `present:generator-asserted` against rows nobody
    # re-derived from a body; `unresolved:…` is an exact identity whose table could not be read.
    # Scoped membership is the evidence join's question and is deliberately NOT asked here: a table
    # cannot be attested until its references exist, and they come from this manifest.
    case "$kind" in
      model=present:compiler-linked)    DEPVC=$((DEPVC+1)) ;;
      model=present:generator-asserted) DEPVG=$((DEPVG+1)) ;;
      model=unresolved:*)               DEPUN=$((DEPUN+1)) ;;
      *) refuse "dependency attestation for $mod.$decl carries an unrecognised model state '$kind'" ;;
    esac
    echo "$tbl <- $pkg/$mod.$decl impl=$impl  binding_role=dependency  $kind  # requested by $cname [$consumer] ($src)" >> "$TMP/depatt.txt"
  fi
done < "$TMP/deprows.tsv"

echo "[dependency-attestations]"
sort "$TMP/depatt.txt"
echo
echo "[dependency-refusals]"
sort "$TMP/depref.txt"
echo

# DUPLICATE and CONFLICTING, on the dependency key exactly as on the subject key. A duplicate means
# one request was counted twice; a conflict means one (consumer, table, callee) resolved to two
# different implementations, which is the shape where either could be selected and one is wrong.
DEPDUPES="$(sort "$TMP/deppairs.tsv" | uniq -d | wc -l)"
DEPCONFLICTS="$(awk -F'\t' '{ key = $1 FS $2 FS $3 FS $4 FS $5; if (!(key in seen)) { seen[key] = $6 }
                                else if (seen[key] != $6) { bad[key] = 1 } }
                              END { n = 0; for (k in bad) n++; print n }' "$TMP/deppairs.tsv")"
[ "${DEPCONFLICTS:-0}" -eq 0 ] || refuse "$DEPCONFLICTS dependency conflict(s) — one (consumer, table, callee) with two implementations"

# --- exact join refusals ---# --- exact join refusals -------------------------------------------------------------------------
# DUPLICATE: the identical mapping emitted twice. Harmless-looking, but it means one input row was
# counted twice, so every denominator built on it is wrong.
DUPES="$(sort "$TMP/pairs.tsv" | uniq -d | wc -l)"
[ "$DUPES" -eq 0 ] || refuse "$DUPES duplicate identical mapping(s) — an input row was counted twice"

# CONFLICTING: one (table, package, module, decl) attested to DIFFERENT implementations. This is the
# dangerous one: both mappings look valid, and a converter taking either would attest a table to an
# implementation the subject does not have.
# Grouped with awk over the WHOLE key, rather than reconstructing a key string and grepping for it.
# The grep version went SILENTLY INERT when the key's field set changed — it found nothing and
# reported no conflicts — so a mutation that altered the key survived. A check that answers "no
# problems" when it has stopped looking is the failure mode this codebase keeps finding.
CONFLICTS="$(awk -F'\t' '{ key = $1 FS $2 FS $3 FS $4; if (!(key in seen)) { seen[key] = $5 }
                            else if (seen[key] != $5) { bad[key] = 1 } }
                          END { n = 0; for (k in bad) n++; print n }' "$TMP/pairs.tsv")"

# SURPLUS: a table attested by no classification row at all. Such a mapping authorises material
# nothing references, which is evidence supplied to an operation that did not request it.
# Digits are part of table names — `Examples.HmacSha256.Proofs.shaFns`. An earlier character class
# of `[A-Za-z][A-Za-z.]*` excluded them and reported a real table as SURPLUS, which is a refusal
# manufactured by the checker rather than found in the data.
KNOWN_TABLES="$(grep -oE '\("[A-Za-z][A-Za-z0-9._]*", "[0-9a-f]{32}"\)' Concrete/Proof/ClassificationTable.lean \
                  | grep -oE '"[A-Za-z][A-Za-z0-9._]*"' | tr -d '"' | sort -u)"
SURPLUS=0
for t in $(cut -f1 "$TMP/pairs.tsv" | sort -u); do
  has_match -x "$t" <<<"$KNOWN_TABLES" || { refuse "table '$t' is attested but referenced by no classification row (surplus)"; SURPLUS=$((SURPLUS+1)); }
done

# --- typed reconciliation: every input row ends mapped, excluded, or refused ---------------------
echo "[reconciliation]"
echo "fixtures_scanned        = $SCANNED"
echo "fixtures_excluded_drift = $EXCLUDED"
echo "subject_rows            = $SUBJECTS"
echo "subjects_no_identity    = $NOID"
echo "subjects_without_table  = $UNTABLED"
echo "table_attestations      = $MAPPED"
echo "duplicate_mappings      = $DUPES"
echo "package_collapse_keys   = ${CONFLICTS:-0}"  # same pkg+decl, different impl
echo "surplus_tables          = $SURPLUS"
# SEPARATE COUNTERS, deliberately. Dependency rows must not inflate `table_attestations`: the 86/48
# subject accounting is frozen, and a population that silently joined it would make the frozen
# denominator meaningless.
echo "dependency_requests     = $DEPREQ"
echo "dependency_attestations = $DEPATT"
echo "dependency_refusals     = $DEPREF"
echo "dependency_duplicate_mappings = $DEPDUPES"
echo "dependency_conflicts    = ${DEPCONFLICTS:-0}"
echo "dependency_without_identity = $DEPNOID"
echo "dependency_model_present_compiler  = $DEPVC"
echo "dependency_model_present_asserted  = $DEPVG"
echo "dependency_model_unresolved        = $DEPUN"
if [ "$DEPATT" -ne $(( DEPVC + DEPVG + DEPUN )) ]; then
  refuse "dependency attestations do not reconcile by model state: $DEPATT != $DEPVC + $DEPVG + $DEPUN"
fi
# EVERY REQUEST ENDS SOMEWHERE. Same typed-reconciliation discipline as the subject rows: a request
# that is neither attested nor refused would be a silently dropped edge.
if [ "$DEPREQ" -ne $(( DEPATT + DEPREF )) ]; then
  refuse "dependency requests do not reconcile: $DEPREQ != $DEPATT + $DEPREF"
fi
ACCOUNTED=$(( NOID + UNTABLED ))
WITH_TABLE=$(( SUBJECTS - ACCOUNTED ))
echo "subjects_with_table     = $WITH_TABLE"

# Every subject row must be accounted for exactly once: no identity, no table, or attested.
if [ "$SUBJECTS" -ne $(( NOID + UNTABLED + WITH_TABLE )) ]; then
  refuse "subject rows do not reconcile: $SUBJECTS != $NOID + $UNTABLED + $WITH_TABLE"
fi
[ "$SUBJECTS" -gt 0 ] || refuse "no subject rows — either the corpus scan or the compiler report broke"
[ "$MAPPED" -gt 0 ]   || refuse "no table attestations emitted — the manifest would authorise nothing"
[ -n "$DRIFT" ]       || refuse "no drift fixtures classified — the classifier stopped matching"

if [ "$REFUSALS" -gt 0 ]; then
  echo "MANIFEST REFUSED: $REFUSALS problem(s)" >&2
  exit 1
fi
