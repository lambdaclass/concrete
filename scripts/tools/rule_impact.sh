#!/usr/bin/env bash
# RULE IMPACT — which programs a candidate compiler accepts or refuses differently from a base
# compiler, before a new language rule lands.
#
# Both compilers compile ONE corpus (by default the base tree's): every standalone .con under
# tests/ and examples/, every project (a directory with Concrete.toml) under tests/ and examples/,
# std (one unit: lib.con with all its modules), and every Concrete program written inline in a gate script
# (a heredoc in scripts/tests/*.sh or scripts/ci/*.sh whose body declares `fn`). Each unit is
# compiled to LLVM IR (`--emit-llvm`, no linking), and its outcome is recorded: accept, refuse
# (with its sorted set of diagnostic codes), crash, or timeout. The report lists every unit whose
# outcome or code set differs, so a rule's breakage is visible as rows such as
# `tests/programs/foo.con  accept -  ->  refuse E0301` before the rule's branch lands.
#
# Both compilers see the corpus's std (CONCRETE_STD=<corpus>/std), so a difference comes from the
# compiler, not from std drift between the two trees. A rule that refuses part of std refuses every
# importer too; the `loc` column (the file of the first diagnostic) separates those rows: `std/...`
# means the refusal is inside std.
#
# Not covered: Concrete programs generated by Python gate code or fuzz generators, inline programs
# whose heredoc expands shell variables (`$`), and outcomes after LLVM (llvm-as, link, run). Those
# need the full gate set.
#
# Usage:
#   scripts/tools/rule_impact.sh --candidate <tree|ref> [--base <tree|ref>] [--corpus <tree|ref>]
#                                [--out DIR] [--jobs N] [--timeout SECONDS] [--only KINDS]
#     <tree>  a checkout whose .lake/build/bin/concrete is already built
#     <ref>   a git ref of this repository: checked out as a temporary worktree, seeded with this
#             tree's .lake and built with `lake build concrete` (run it on a build server)
#     --base    default: this tree (it must be built)
#     --corpus  default: the base. A ref is exported with `git archive`; a tree is copied (tracked
#               and untracked, not ignored, files), so builds never write into a checkout
#     --only    comma list of unit kinds: file,project,std,inline (default all)
#     --jobs    parallel compiles (default: nproc / 2, at most 32)
# Output (DIR, default a temp dir, printed): base.tsv, candidate.tsv, diff.tsv, summary.txt, and
# logs/{base,candidate}/<unit with / as %>.err (the full diagnostics of every refusal).
#   columns: kind  unit  outcome  codes  loc  first-error-line
# Exit: 0 no difference, 1 differences found, 2 usage or setup error.
set -uo pipefail
export LC_ALL=C

# --- worker mode: compile one unit, print one TSV row -----------------------------------------
if [ "${1:-}" = "__unit" ]; then
  compiler="$2"; corpus="$3"; tmo="$4"; logs="$5"; kind="$6"; unit="$7"
  export CONCRETE_STD="$corpus/std"
  out=$(mktemp)
  case "$kind" in
    file|inline) (cd "$corpus" && timeout "$tmo" "$compiler" "$unit" --emit-llvm >/dev/null 2>"$out"); rc=$? ;;
    project) (cd "$corpus/$unit" && timeout "$tmo" "$compiler" build --emit-llvm >/dev/null 2>"$out"); rc=$? ;;
    std) (cd "$corpus" && timeout "$tmo" "$compiler" "$unit" --emit-llvm >/dev/null 2>"$out"); rc=$? ;;
  esac
  # Diagnostics render as `error[check]: (E0301) ...`; a code inside a hint is not the error's own.
  codes=$(grep -oE '(error|warning)[^:]*: \(E[0-9]{4}\)' "$out" | grep -oE 'E[0-9]{4}' | sort -u | paste -sd, -)
  first=$(grep -m1 -E 'error' "$out" | tr '\t' ' ' | cut -c1-240)
  loc=$(printf '%s' "$first" | grep -oE '^[^ :]+\.con' | sed "s|^$corpus/||")
  if [ $rc -eq 0 ]; then outcome=accept
  elif [ $rc -eq 124 ]; then outcome=timeout
  elif [ $rc -ge 128 ] || grep -qiE 'PANIC|INTERNAL PANIC|uncaught exception|stack overflow' "$out"; then outcome=crash
  else outcome=refuse; fi
  [ "$outcome" = accept ] && { codes=""; first=""; loc=""; }
  # Keep every refusal's full diagnostics: a unit reports more than its first error.
  [ "$outcome" = accept ] || cp "$out" "$logs/$(printf '%s' "$unit" | tr '/' '%').err"
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$kind" "$unit" "$outcome" "${codes:--}" "${loc:--}" "${first:--}"
  rm -f "$out"
  exit 0
fi

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SELF="$ROOT_DIR/scripts/tools/rule_impact.sh"
die() { echo "rule_impact: $*" >&2; exit 2; }

CAND=""; BASE="$ROOT_DIR"; CORPUS=""; OUT=""; ONLY="file,project,std,inline"; TMO=120
NPROC=$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4)
JOBS=$(( NPROC / 2 )); [ "$JOBS" -lt 1 ] && JOBS=1; [ "$JOBS" -gt 32 ] && JOBS=32
while [ $# -gt 0 ]; do
  case "$1" in
    --candidate) CAND="${2:-}"; shift 2 ;;
    --base) BASE="${2:-}"; shift 2 ;;
    --corpus) CORPUS="${2:-}"; shift 2 ;;
    --out) OUT="${2:-}"; shift 2 ;;
    --jobs) JOBS="${2:-}"; shift 2 ;;
    --timeout) TMO="${2:-}"; shift 2 ;;
    --only) ONLY="${2:-}"; shift 2 ;;
    -h|--help) sed -n '2,40p' "$0"; exit 0 ;;
    *) die "unknown argument '$1' (see --help)" ;;
  esac
done
[ -n "$CAND" ] || die "--candidate is required"
case "$JOBS$TMO" in *[!0-9]*) die "--jobs and --timeout take positive integers" ;; esac
[ -n "$CORPUS" ] || CORPUS="$BASE"
WORK=$(mktemp -d "${TMPDIR:-/tmp}/rule_impact.XXXXXX")
[ -n "$OUT" ] || OUT="$WORK/report"
mkdir -p "$OUT"
WORKTREES=()
cleanup() {
  for w in "${WORKTREES[@]+"${WORKTREES[@]}"}"; do git -C "$ROOT_DIR" worktree remove --force "$w" >/dev/null 2>&1; done
  rm -rf "$WORK/trees" "$WORK/corpus"
}
trap cleanup EXIT

# resolve <tree|ref> <label>: set RESOLVED to a directory holding a built compiler. Not run in a
# subshell, so a temporary worktree is registered for cleanup and `die` ends the script.
resolve() {
  local spec="$1" label="$2" dir
  if [ -d "$spec" ]; then
    dir="$(cd "$spec" && pwd)"
    [ -x "$dir/.lake/build/bin/concrete" ] || die "$label tree $dir has no built .lake/build/bin/concrete"
    RESOLVED="$dir"; return
  fi
  git -C "$ROOT_DIR" rev-parse --verify --quiet "$spec^{commit}" >/dev/null || die "$label '$spec' is neither a directory nor a commit"
  dir="$WORK/trees/$label"; mkdir -p "$WORK/trees"
  git -C "$ROOT_DIR" worktree add --quiet --detach "$dir" "$spec" >&2 || die "cannot check out $spec"
  WORKTREES+=("$dir")
  [ -d "$ROOT_DIR/.lake" ] && cp -a "$ROOT_DIR/.lake" "$dir/.lake"
  echo "rule_impact: building $label ($spec) in $dir" >&2
  (cd "$dir" && lake build concrete >"$WORK/build-$label.log" 2>&1) || { tail -20 "$WORK/build-$label.log" >&2; die "build of $spec failed"; }
  RESOLVED="$dir"
}

RESOLVED=""
resolve "$BASE" base; BASE_DIR="$RESOLVED"
resolve "$CAND" candidate; CAND_DIR="$RESOLVED"

# --- the corpus: a private copy, so project builds never write into a checkout ---------------
CDIR="$WORK/corpus"; mkdir -p "$CDIR"
if [ -d "$CORPUS" ]; then
  CORPUS_DESC="tree $(cd "$CORPUS" && pwd) @ $(git -C "$CORPUS" rev-parse --short HEAD 2>/dev/null || echo '?') (working copy)"
  (cd "$CORPUS" && git ls-files -co --exclude-standard -- tests examples std scripts | tar -cf - -T -) | tar -xf - -C "$CDIR" \
    || die "cannot copy corpus $CORPUS"
else
  git -C "$ROOT_DIR" rev-parse --verify --quiet "$CORPUS^{commit}" >/dev/null || die "corpus '$CORPUS' is neither a directory nor a commit"
  CORPUS_DESC="ref $CORPUS @ $(git -C "$ROOT_DIR" rev-parse --short "$CORPUS")"
  git -C "$ROOT_DIR" archive "$CORPUS" tests examples std scripts | tar -xf - -C "$CDIR" || die "cannot export corpus $CORPUS"
fi

# --- enumerate units ------------------------------------------------------------------------
UNITS="$WORK/units.tsv"; : > "$UNITS"
want() { case ",$ONLY," in *",$1,"*) return 0 ;; esac; return 1; }
(
  cd "$CDIR"
  projects=$(find tests examples -name Concrete.toml -not -path '*/.*' 2>/dev/null | while read -r t; do dirname "$t"; done | sort)
  if want project; then printf '%s\n' "$projects" | sed '/^$/d; s/^/project\t/'; fi
  if want file; then
    find tests examples -name '*.con' -not -path '*/.*' | sort | while read -r f; do
      inproj=0
      for p in $projects; do case "$f" in "$p"/*) inproj=1; break ;; esac; done
      [ $inproj = 0 ] && printf 'file\t%s\n' "$f"
    done
  fi
  # std is one compilation unit (lib.con resolves every module; `--test --module` links and runs
  # tests, it does not select a module to check), so it is one unit whose full diagnostic list the
  # summary prints.
  if want std && [ -f std/src/lib.con ]; then printf 'std\tstd/src/lib.con\n'; fi
) >> "$UNITS"
if want inline; then
  mkdir -p "$CDIR/_inline"
  for s in "$CDIR"/scripts/tests/*.sh "$CDIR"/scripts/ci/*.sh; do
    [ -f "$s" ] || continue
    # A heredoc body is a Concrete program when it declares a function and expands no shell
    # variable. The delimiter is the word after <<, quoted or not; `<<-` strips leading tabs.
    awk -v out="$CDIR/_inline" -v base="$(basename "$s" .sh)" '
      function flush() {
        if (body ~ /(^|\n)[ \t]*(pub[ \t]+)?(trusted[ \t]+)?fn[ \t]+[A-Za-z_]/ && !(quoted == 0 && body ~ /\$/)) {
          f = out "/" base "__L" start ".con"; printf "%s", body > f; close(f); print "inline\t_inline/" base "__L" start ".con"
        }
      }
      inbody == 0 {
        if (match($0, /<<-?[ \t]*["\047]?[A-Za-z_][A-Za-z0-9_]*["\047]?/)) {
          tok = substr($0, RSTART, RLENGTH); quoted = (tok ~ /["\047]/)
          dash = (tok ~ /^<<-/); gsub(/^<<-?[ \t]*|["\047]/, "", tok)
          delim = tok; inbody = 1; body = ""; start = NR + 1
        }
        next
      }
      {
        line = $0; if (dash) sub(/^\t+/, "", line)
        if (line == delim) { inbody = 0; flush(); next }
        body = body $0 "\n"
      }' "$s"
  done | sort >> "$UNITS"
fi
N=$(wc -l < "$UNITS" | tr -d ' ')
[ "$N" -gt 0 ] || die "no units found in the corpus"
echo "rule_impact: $N units ($(cut -f1 "$UNITS" | sort | uniq -c | awk '{printf "%s %s, ", $1, $2}' | sed 's/, $//')); corpus $CORPUS_DESC; jobs $JOBS" >&2

# Workers get the fixed arguments first; xargs appends "<kind> <unit>".
run_side() {
  local compiler="$1" dest="$2" logs="$3"
  mkdir -p "$logs"
  while IFS=$'\t' read -r kind unit; do printf '%s\0%s\0' "$kind" "$unit"; done < "$UNITS" \
    | xargs -0 -n2 -P "$JOBS" bash "$SELF" __unit "$compiler" "$CDIR" "$TMO" "$logs" \
    | sort -t$'\t' -k2,2 > "$dest"
}
echo "rule_impact: base      $BASE_DIR @ $(git -C "$BASE_DIR" rev-parse --short HEAD 2>/dev/null)" >&2
echo "rule_impact: candidate $CAND_DIR @ $(git -C "$CAND_DIR" rev-parse --short HEAD 2>/dev/null)" >&2
run_side "$BASE_DIR/.lake/build/bin/concrete" "$OUT/base.tsv" "$OUT/logs/base"
run_side "$CAND_DIR/.lake/build/bin/concrete" "$OUT/candidate.tsv" "$OUT/logs/candidate"
nb=$(wc -l < "$OUT/base.tsv" | tr -d ' '); nc=$(wc -l < "$OUT/candidate.tsv" | tr -d ' ')
[ "$nb" = "$N" ] && [ "$nc" = "$N" ] || die "incomplete scan: $N units, base $nb rows, candidate $nc rows"

# --- diff: a unit differs when its outcome or its code set differs --------------------------
join -t$'\t' -1 2 -2 2 -o '1.1,1.2,1.3,1.4,2.3,2.4,2.5,2.6' "$OUT/base.tsv" "$OUT/candidate.tsv" \
  | awk -F'\t' -v OFS='\t' '$3 != $5 || $4 != $6 { print $1, $2, $3, $4, $5, $6, $7, $8 }' > "$OUT/diff.tsv"
D=$(wc -l < "$OUT/diff.tsv" | tr -d ' ')
{
  echo "rule impact: candidate $(git -C "$CAND_DIR" rev-parse --short HEAD 2>/dev/null) vs base $(git -C "$BASE_DIR" rev-parse --short HEAD 2>/dev/null)"
  echo "corpus: $CORPUS_DESC"
  echo "units: $N; differing: $D"
  echo
  echo "outcomes (base -> candidate, count):"
  cut -f3,5 "$OUT/diff.tsv" | sort | uniq -c | awk '{printf "  %-8s -> %-8s %s\n", $2, $3, $1}'
  echo
  echo "newly refused, by candidate code set (inside std / in the unit itself):"
  awk -F'\t' '$3 == "accept" && $5 != "accept" { w = ($7 ~ /^std\//) ? "std" : "unit"; print $6 "\t" w }' "$OUT/diff.tsv" \
    | sort | uniq -c | awk '{printf "  %-24s %-5s %s\n", $2, $3, $1}'
  echo
  echo "still refused, code set changed (base -> candidate):"
  awk -F'\t' '$3 != "accept" && $5 != "accept" { print $4 " -> " $6 }' "$OUT/diff.tsv" | sort | uniq -c | sed 's/^/  /'
  echo
  coded() { [ -f "$1" ] && grep -oE '^[^ ]+\.con:[0-9]+:[0-9]+: error[^:]*: \(E[0-9]{4}\)' "$1" | sed -E 's/: error[^(]*\((E[0-9]{4})\)/ \1/' | sort -u; }
  stdlog="std%src%lib.con.err"
  if [ -f "$OUT/logs/candidate/$stdlog" ]; then
    echo "std diagnostics under the candidate that the base does not report (file:line:col code):"
    comm -13 <(coded "$OUT/logs/base/$stdlog") <(coded "$OUT/logs/candidate/$stdlog") | sed "s|^$CDIR/||; s/^/  /"
    echo
  fi
  echo "by kind:"
  cut -f1 "$OUT/diff.tsv" | sort | uniq -c | sed 's/^/  /'
  echo
  echo "rows (kind, unit, base outcome, base codes -> candidate outcome, candidate codes, loc):"
  awk -F'\t' '{ printf "  %-7s %s  %s %s -> %s %s  [%s]\n", $1, $2, $3, $4, $5, $6, $7 }' "$OUT/diff.tsv"
} > "$OUT/summary.txt"
printf 'kind\tunit\tbase\tbase_codes\tcandidate\tcandidate_codes\tcandidate_loc\tcandidate_first_error\n' \
  | cat - "$OUT/diff.tsv" > "$OUT/diff.tsv.tmp" && mv "$OUT/diff.tsv.tmp" "$OUT/diff.tsv"
cat "$OUT/summary.txt"
echo "rule_impact: report in $OUT" >&2
[ "$D" -eq 0 ]
