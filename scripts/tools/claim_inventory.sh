#!/usr/bin/env bash
# FROZEN CLAIM INVENTORY (R-0208 Lean upgrade): every Lean-backed claim in the corpus, with what the
# current checker says about it, in a stable, diffable form.
#
# The upgrade must replay the SAME denominator before and after, and every evidence change must be
# explained. So the inventory is generated on the old checker, committed, regenerated on the new one,
# and compared row by row — never regenerated to make a difference disappear.
#
# Rows: one per (source, function, theorem, kind): the lookup status, the fresh kernel re-check
# verdict, and whether issuance minted a receipt (with its refusal when it did not). The header
# names the checker that produced the rows; the ROWS are what must be compared across checkers.
#
# Usage: scripts/tools/claim_inventory.sh > docs/verification/claim-inventory.tsv
set -uo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"
BIN="$ROOT_DIR/.lake/build/bin/concrete"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
mapfile -t SOURCES < <(grep -rl '#\[proof_by' examples tests 2>/dev/null | grep '\.con$' | LC_ALL=C sort)
CHECKER=""
ROWS="$TMP/rows"; : > "$ROWS"
# SOURCES ARE REPLAYED CONCURRENTLY (R-0547). Each source is two compiler runs and a batch of Lean
# processes (about 7.6 s), independent of every other source, and the 59 of them in series made
# check_claim_inventory.sh a 4-minute gate. Each source writes its rows to its own file in its own
# directory; the output is the same rows, sorted as before, so the inventory is byte-identical.
# CLAIM_INVENTORY_JOBS bounds the fan-out (default: half the cores, at most 8).
_cores="$( (nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null) || echo 2)"
CI_JOBS="${CLAIM_INVENTORY_JOBS:-$(( _cores / 2 ))}"
[ "$CI_JOBS" -ge 1 ] 2>/dev/null || CI_JOBS=1
[ -n "${CLAIM_INVENTORY_JOBS:-}" ] || [ "$CI_JOBS" -le 8 ] || CI_JOBS=8
replay_one() { # index source
  local d="$TMP/s$1" src="$2"
  mkdir -p "$d"; : > "$d/rows"
  "$BIN" "$src" --report check-proofs --json > "$d/cp.json" 2>/dev/null || true
  "$BIN" "$src" --report receipts --out "$d/r.txt" > "$d/issue.txt" 2>&1 || true
  python3 - "$src" "$d/cp.json" "$d/issue.txt" "$d/rows" "$d/checker" <<'PY'
import json, re, sys
src, cp, issue, rows, ck = sys.argv[1:]
try:
    d = json.load(open(cp))
except Exception:
    d = {"checks": [], "refusal": "no_json"}
if d.get("checker"):
    open(ck, "w").write(d["checker"])
issue_txt = open(issue).read()
# Issuance lists minted receipts as "+ subject — ..." and withheld ones as "- subject [reason] ...".
minted = set(re.findall(r"^\s+\+ (\S+) —", issue_txt, re.M))
withheld = {m.group(1): m.group(2) for m in re.finditer(r"^\s+- (\S+) \[([a-z_]+)\]", issue_txt, re.M)}
with open(rows, "a") as out:
    if not d.get("checks"):
        out.write(f"{src}\t-\t-\t-\t{d.get('refusal', 'no_checks')}\t-\t-\n")
    for c in d.get("checks", []):
        fn = c.get("function", "?")
        receipt = "minted" if fn in minted else ("withheld:" + withheld[fn] if fn in withheld else "none")
        out.write("\t".join([src, fn, c.get("theorem", "?"), c.get("obligation_kind", "?"),
                             c.get("status", "?"), c.get("recheck", "?"), receipt]) + "\n")
PY
  echo done > "$d/finished"
}
for (( i=0; i<${#SOURCES[@]}; i++ )); do
  while [ "$(jobs -rp | wc -l)" -ge "$CI_JOBS" ]; do wait -n 2>/dev/null || true; done
  replay_one "$i" "${SOURCES[$i]}" &
done
wait
# EVERY SOURCE MUST HAVE FINISHED. A replay that died leaves no marker, and its missing rows would
# otherwise read as a smaller inventory; a missing source is reported as a row the diff will show.
for (( i=0; i<${#SOURCES[@]}; i++ )); do
  if [ -f "$TMP/s$i/finished" ]; then cat "$TMP/s$i/rows" >> "$ROWS"
  else printf '%s\t-\t-\t-\treplay_died\t-\t-\n' "${SOURCES[$i]}" >> "$ROWS"; fi
  [ -n "$CHECKER" ] || { [ -s "$TMP/s$i/checker" ] && CHECKER="$(cat "$TMP/s$i/checker")"; }
done
echo "# Frozen claim inventory (R-0208). Generated by scripts/tools/claim_inventory.sh."
echo "# checker: ${CHECKER:-UNIDENTIFIED}"
echo "# sources: ${#SOURCES[@]}  claims: $(grep -vc $'\t-\t-\t-\t' "$ROWS")"
printf '# source\tfunction\ttheorem\tkind\tlookup\trecheck\treceipt\n'
LC_ALL=C sort "$ROWS"
