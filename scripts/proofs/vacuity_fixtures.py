"""Verify exact historical evidence bytes and law-specific server diagnostics.

Without --reports this is a light provenance check. Reports must be generated by
vacuity.sh on the archived commit specified in provenance.json, with the fixture's
proof module included in the scope. The report filename is <label>.txt.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import io
import tarfile
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def replay(records, directory):
    """Server-only historical controls: fresh sources, exact retained evidence.

    Each report is produced by the ordinary audit, then checked by the same
    exact diagnostic assertions as supplied reports. Never synthesize a PASS.
    """
    directory.mkdir(parents=True, exist_ok=False)
    scopes = {
        'c9-old': ['Ident', 'Prim'], 'c9-new': ['Ident', 'Prim'],
        'c6-old': ['Observe2'], 'c6-current': ['Observe2', 'ObserveEvidence'],
    }
    for label, modules in scopes.items():
        row = next(row for row in records if row['fixture'].startswith(label + '-'))
        with tempfile.TemporaryDirectory(prefix='n2-historical-') as temp:
            archive = subprocess.run(
                ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '30', 'git',
                 'archive', row['commit'], 'ConcreteSpec', 'ConcreteSpec.lean', 'ROADMAP.md'],
                cwd=ROOT, stdout=subprocess.PIPE, check=True)
            with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tree:
                tree.extractall(temp, filter='data')
            command = ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '600',
                       sys.executable, str(HERE / 'vacuity_driver.py'), '--source', temp]
            for module in modules:
                command.extend(['--scope', 'ConcreteSpec.Proofs.' + module])
            result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT)
            (directory / (label + '.txt')).write_bytes(result.stdout)
            if result.returncode not in {0, 1, 2}:
                raise RuntimeError(f'INCOMPLETE historical-replay {label} rc={result.returncode}')


def focused_c9(records):
    """Light exact C9 law/evidence control, using the shared population.

    This is an isolated control, not a historical module or head PASS.
    All source bytes (including retained example line identities) are unchanged.
    """
    from vacuity_driver import compiled_consumer, run
    row = next(row for row in records if row['fixture'].startswith('c9-new-'))
    archive = subprocess.run(
        ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '30', 'git',
         'archive', row['commit'], 'ConcreteSpec', 'ConcreteSpec.lean', 'ROADMAP.md'],
        cwd=ROOT, stdout=subprocess.PIPE, check=True)
    driver = r'''import ConcreteSpec
import N2Meta
open Lean Meta
set_option maxHeartbeats 2000000 in
#eval show MetaM Unit from do
  let population := (populationConstants (← getEnv)).filter fun (n, _) =>
    n == `ConcreteSpec.Core.KeyConstruct.collectKeysIn_sound ||
    (toString n).endsWith "ConcreteSpec/Proofs/Ident.lean:1266»" ||
    (toString n).endsWith "ConcreteSpec/Proofs/Ident.lean:1273»"
  unless population.length == 3 do throwError "exact-c9-population"
  let findings ← Vacuity.check population
  for f in findings do
    IO.println s!"{f.status} {f.code} {f.name} {f.detail}"
  if findings.any (·.status == "INCOMPLETE") then IO.println "N2 INCOMPLETE"
  else if findings.any (·.status == "FAIL") then IO.println "N2 FAIL"
  else IO.println "N2 PASS"
'''
    with tempfile.TemporaryDirectory(prefix='n2-c9-control-') as temp:
        with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tree:
            tree.extractall(temp, filter='data')
        with compiled_consumer() as meta:
            code, output = run(Path(temp), 'ConcreteSpec.Proofs.Ident', inventory=True,
                               driver_text=driver, meta_path=meta)
    # The selected law has two subjects; this exact planted example targets
    # pathAtIn only. Its missing collectKeysIn witness is deliberately retained,
    # and must be the sole failure, on the law rather than either evidence term.
    expected = ('FAIL missing-planted ConcreteSpec.Core.KeyConstruct.collectKeysIn_sound '
                'ConcreteSpec.Core.Vacuity.nestedBody/ConcreteSpec.Core.KeyConstruct.collectKeysIn')
    diagnostics = [line.strip() for line in output.splitlines()
                   if line.startswith(('FAIL ', 'INCOMPLETE '))]
    if code != 0 or diagnostics != [expected] or not output.endswith('N2 FAIL\n'):
        print('FAIL exact-c9-control\n' + output)
        return 1
    print('PASS exact-c9-control: original law, closed instance :1266 and planted :1273; '
          'both evidence checks clean; exact missing sibling-subject witness retained')
    return 0


def focused_c2():
    """Audit only the historical C2 projection proof, at two declared bounds."""
    from vacuity_driver import compiled_consumer, run
    archive = subprocess.run(
        ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '30', 'git',
         'archive', '9cb0ef7fe4f23ac13745717e2e4854410cbf36d1',
         'ConcreteSpec', 'ConcreteSpec.lean', 'ROADMAP.md'],
        cwd=ROOT, stdout=subprocess.PIPE, check=True)
    driver = r'''import ConcreteSpec
import N2Meta
open Lean Meta
set_option maxHeartbeats 2000000 in
#eval show MetaM Unit from do
  let name := `ConcreteSpec.Core.ConstOrderIndependent
  let ci ← getConstInfo name
  let some proof := ci.value? (allowOpaque := true) | throwError "missing-c2-proof"
  for budget in [64, 4096] do
    let ((projection, cost), audit) ← ((Vacuity.direct name proof).run { remaining := budget }).run {}
    unless !projection && audit.findings.isEmpty && cost.remaining > 0 do
      for f in audit.findings do IO.println s!"{f.status} {f.code} {f.name} {f.detail}"
      throwError "c2-projection-incomplete-or-rejected"
    IO.println s!"C2 COMPLETE limit={budget} visited={budget - cost.remaining}"
'''
    with tempfile.TemporaryDirectory(prefix='n2-c2-control-') as temp:
        with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tree:
            tree.extractall(temp, filter='data')
        with compiled_consumer() as meta:
            code, output = run(Path(temp), 'ConcreteSpec.Proofs.Const', inventory=True,
                               driver_text=driver, meta_path=meta)
    lines = output.splitlines()
    if (code != 0 or len(lines) != 2 or
            not lines[0].startswith('C2 COMPLETE limit=64 visited=') or
            not lines[1].startswith('C2 COMPLETE limit=4096 visited=')):
        print('FAIL exact-c2-projection-control\n' + output)
        return 1
    print(output, end='')
    print('PASS exact-c2-projection-control (isolated proof, no head PASS claim)')
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--reports', type=Path)
    parser.add_argument('--replay', type=Path, help='server: re-elaborate all exact historical controls into this report directory')
    parser.add_argument('--focused-c9', action='store_true', help='light isolated exact C9 law and two evidence checks')
    parser.add_argument('--focused-c2', action='store_true', help='light isolated historical C2 projection check')
    args = parser.parse_args()
    records = json.loads((HERE / 'fixtures/provenance.json').read_text())
    if args.focused_c2:
        return focused_c2()
    if args.focused_c9:
        return focused_c9(records)
    if args.replay:
        replay(records, args.replay)
        args.reports = args.replay
    failures = []
    cache = {}
    checked_reports = set()
    for row in records:
        key = row['commit'], row['path']
        if key not in cache:
            result = subprocess.run(['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'),
                                     '20', 'git', 'show', ':'.join(key)],
                                    cwd=ROOT, stdout=subprocess.PIPE, check=True)
            cache[key] = result.stdout
        source = cache[key]
        exact = b''.join(source.splitlines(keepends=True)[row['start'] - 1:row['end']])
        fixture = (HERE / 'fixtures' / row['fixture']).read_bytes()
        if (fixture != exact or hashlib.sha256(source).hexdigest() != row['source_sha256']
                or hashlib.sha256(fixture).hexdigest() != row['sha256']):
            failures.append('FAIL fixture-provenance ' + row['fixture'])
        if args.reports:
            label = row['fixture'].split('-trapLine')[0].split('-collectKeys')[0]
            report = (args.reports / (label + '.txt')).read_text()
            if label not in checked_reports:
                checked_reports.add(label)
                # Clean evidence means a completed audit, never merely the
                # absence of a diagnostic in a killed or partial report.
                lines = report.splitlines()
                if (not lines or lines[-1] not in {'N2 PASS', 'N2 FAIL'} or
                        any(line.startswith('INCOMPLETE ') for line in lines)):
                    failures.append('FAIL report-incomplete ' + label)

            provenance = f'N2 SOURCE-FILE {row["path"]} {row["source_sha256"]}'
            if provenance not in report.splitlines():
                failures.append('FAIL report-source-provenance ' + row['fixture'])
            # The retained declaration name includes the source path and original line.
            marker = f'«⟪example⟫{row["path"]}:'
            example_line = row['start'] + next(
                i for i, text in enumerate(fixture.decode().splitlines()) if text.startswith('example '))
            name_suffix = marker + str(example_line) + '»'
            diagnostics = [line.split()[:3] for line in report.splitlines()
                           if name_suffix in line and line.startswith(('FAIL ', 'INCOMPLETE '))]
            kind = 'instance' if '-instance-' in row['fixture'] else 'planted'
            code = 'instance-application' if kind == 'instance' else 'planted-proposition'
            bad = label in {'c9-old', 'c6-old'}
            exact_reason = [parts for parts in diagnostics if parts[:2] == ['FAIL', code]]
            if bad and len(exact_reason) != 1:
                failures.append(f'FAIL fixture-diagnostic {row["fixture"]} expected FAIL {code}')
            if not bad and diagnostics:
                failures.append(f'FAIL fixture-diagnostic {row["fixture"]} expected clean evidence: {diagnostics}')
    if failures:
        print('\n'.join(failures)); return 1
    print(f'PASS real fixture provenance: {len(records)} byte-for-byte excerpts')
    if args.reports:
        print('PASS real fixture diagnostics (exact codes and retained declaration identities)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
