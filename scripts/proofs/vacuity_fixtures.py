"""Verify exact historical evidence bytes and law-specific server diagnostics.

Without --reports this is a light provenance check. Reports must be generated by
vacuity.sh on the archived commit specified in provenance.json, with the fixture's
proof module included in the scope. The report filename is <label>.txt.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import io
import tarfile
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def replay(records, directory):
    """Server-only historical controls: fresh sources, exact retained evidence.

    Each report is produced by the ordinary audit, then checked by the same
    exact diagnostic assertions as supplied reports. Never synthesize a PASS.
    """
    directory.mkdir(parents=True, exist_ok=True)
    scopes = {
        'c9-old': ['Ident', 'Prim'], 'c9-new': ['Ident', 'Prim'],
        'c6-old': ['Observe2'], 'c6-current': ['Observe2', 'ObserveEvidence'],
    }
    for label, modules in scopes.items():
        row = next(row for row in records if row['fixture'].startswith(label + '-'))
        with tempfile.TemporaryDirectory(prefix='n2-historical-') as temp:
            archive = subprocess.run(
                ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '30', 'git',
                 'archive', row['commit'], 'ConcreteSpec', 'ConcreteSpec.lean', 'ROADMAP.md'],
                cwd=ROOT, stdout=subprocess.PIPE, check=True)
            with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tree:
                tree.extractall(temp, filter='data')
            command = ['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'), '600',
                       sys.executable, str(HERE / 'vacuity_driver.py'), '--source', temp]
            for module in modules:
                command.extend(['--scope', 'ConcreteSpec.Proofs.' + module])
            result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT)
            (directory / (label + '.txt')).write_bytes(result.stdout)
            if result.returncode not in {0, 1, 2}:
                raise RuntimeError(f'INCOMPLETE historical-replay {label} rc={result.returncode}')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--reports', type=Path)
    parser.add_argument('--replay', type=Path, help='server: re-elaborate all exact historical controls into this report directory')
    args = parser.parse_args()
    records = json.loads((HERE / 'fixtures/provenance.json').read_text())
    if args.replay:
        replay(records, args.replay)
        args.reports = args.replay
    failures = []
    cache = {}
    checked_reports = set()
    for row in records:
        key = row['commit'], row['path']
        if key not in cache:
            result = subprocess.run(['bash', str(ROOT / 'scripts/checks/lib/bounded.sh'),
                                     '20', 'git', 'show', ':'.join(key)],
                                    cwd=ROOT, stdout=subprocess.PIPE, check=True)
            cache[key] = result.stdout
        source = cache[key]
        exact = b''.join(source.splitlines(keepends=True)[row['start'] - 1:row['end']])
        fixture = (HERE / 'fixtures' / row['fixture']).read_bytes()
        if (fixture != exact or hashlib.sha256(source).hexdigest() != row['source_sha256']
                or hashlib.sha256(fixture).hexdigest() != row['sha256']):
            failures.append('FAIL fixture-provenance ' + row['fixture'])
        if args.reports:
            label = row['fixture'].split('-trapLine')[0].split('-collectKeys')[0]
            report = (args.reports / (label + '.txt')).read_text()
            if label not in checked_reports:
                checked_reports.add(label)
                # Clean evidence means a completed audit, never merely the
                # absence of a diagnostic in a killed or partial report.
                lines = report.splitlines()
                if (not lines or lines[-1] not in {'N2 PASS', 'N2 FAIL'} or
                        any(line.startswith('INCOMPLETE ') for line in lines)):
                    failures.append('FAIL report-incomplete ' + label)

            provenance = f'N2 SOURCE-FILE {row["path"]} {row["source_sha256"]}'
            if provenance not in report.splitlines():
                failures.append('FAIL report-source-provenance ' + row['fixture'])
            # The retained declaration name includes the source path and original line.
            marker = f'«⟪example⟫{row["path"]}:'
            example_line = row['start'] + next(
                i for i, text in enumerate(fixture.decode().splitlines()) if text.startswith('example '))
            name_suffix = marker + str(example_line) + '»'
            diagnostics = [line.split()[:3] for line in report.splitlines()
                           if name_suffix in line and line.startswith(('FAIL ', 'INCOMPLETE '))]
            kind = 'instance' if '-instance-' in row['fixture'] else 'planted'
            code = 'instance-application' if kind == 'instance' else 'planted-proposition'
            bad = label in {'c9-old', 'c6-old'}
            exact_reason = [parts for parts in diagnostics if parts[:2] == ['FAIL', code]]
            if bad and len(exact_reason) != 1:
                failures.append(f'FAIL fixture-diagnostic {row["fixture"]} expected FAIL {code}')
            if not bad and diagnostics:
                failures.append(f'FAIL fixture-diagnostic {row["fixture"]} expected clean evidence: {diagnostics}')
    if failures:
        print('\n'.join(failures)); return 1
    print(f'PASS real fixture provenance: {len(records)} byte-for-byte excerpts')
    if args.reports:
        print('PASS real fixture diagnostics (exact codes and retained declaration identities)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
