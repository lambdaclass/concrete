#!/usr/bin/env python3
"""The one reader of scripts/checks/legacy.lock, the record legacy_frozen.sh judges legacy/ against.

No other code reads the lock's bytes: legacy_frozen.sh and doc_links.py take its rows from here, and
legacy_frozen.sh's controls refuse any other reader. One parser means every consumer sees the same
rows, so no byte can be a row to one check and not to another.

THE FORMAT. Every line ends with a newline (LF) and is exactly one row:
  line 1     base <commit>            the move's base commit
  line 2     tree <tree>              that commit's tree: the frozen legacy/
  line 3...  sweep <commit> <tree>    one per sweep: its source commit and the legacy/ tree it produced
An <oid> is 40 or 64 lowercase hex digits; one space separates the fields. Nothing else is a row:
no blank line, comment, NUL, CR, tab, leading or trailing space, non-ASCII byte, repeated row, or
last line without its newline. A `preview` line (a move generated by --preview) is refused with
its own message. Every problem is reported, one diagnostic per line, as NAME:LINE: message.

Usage:
  legacy_lock.py rows FILE|-              print the rows, one per line; exit 1 with the diagnostics
  legacy_lock.py history LOCK PATH TRUSTED
      every row of every version of PATH in TRUSTED's first-parent history (each commit read
      against its first parent) is a row of LOCK: rows are only ever added. A malformed trusted
      version is refused, not skipped. Prints one refusal per problem; exit 1 if any.
Exit 2 on a usage or I/O error.
"""

import re
import subprocess
import sys

LOCK_PATH = "scripts/checks/legacy.lock"
OID = r"(?:[0-9a-f]{40}|[0-9a-f]{64})"
FORMS = {
    "base": re.compile(rf"base {OID}"),
    "tree": re.compile(rf"tree {OID}"),
    "sweep": re.compile(rf"sweep {OID} {OID}"),
}
PREVIEW = re.compile(r"preview(?: .*)?")


class LockError(ValueError):
    """The lock is malformed; .problems holds one diagnostic per problem."""

    def __init__(self, problems):
        super().__init__("\n".join(problems))
        self.problems = problems


def parse(data, name):
    """The rows of a lock's bytes, as strings ('base X', 'tree X', 'sweep X Y'), in order."""
    if not data:
        raise LockError([f"{name}: empty: line 1 must be 'base <commit>'"])
    lines = data.split(b"\n")
    last_unterminated = lines[-1] != b""
    if not last_unterminated:
        lines.pop()
    problems, rows, seen = [], [], {}
    for n, raw in enumerate(lines, 1):
        where = f"{name}:{n}"
        if b"\0" in raw:
            problems.append(f"{where}: holds a NUL byte: the lock is text"); continue
        if b"\r" in raw:
            problems.append(f"{where}: holds a carriage return: a line ends with a newline (LF) alone"); continue
        try:
            line = raw.decode("ascii")
        except UnicodeDecodeError:
            problems.append(f"{where}: holds a non-ASCII byte"); continue
        if n == len(lines) and last_unterminated:
            problems.append(f"{where}: has no newline: every line, the last too, ends with one"); continue
        want = "base" if n == 1 else "tree" if n == 2 else "sweep"
        if PREVIEW.fullmatch(line):
            problems.append(f"{where}: the move is a --preview build ({line}); a lock may only record a move "
                            "generated with its landing prerequisites met (the generator is "
                            "legacy/scripts/land/legacy_move.sh since the 2026-11-08 sweep)"); continue
        if not FORMS[want].fullmatch(line):
            shape = {"base": "'base <commit>'", "tree": "'tree <tree>'", "sweep": "'sweep <commit> <tree>'"}[want]
            problems.append(f"{where}: is not a lock row: line {n} must be {shape}, one space between "
                            "fields, each oid 40 or 64 lowercase hex digits"); continue
        if line in seen:
            problems.append(f"{where}: repeats line {seen[line]}: a row is recorded once"); continue
        seen[line] = n
        rows.append(line)
    if problems:
        raise LockError(problems)
    return rows


def read(path):
    """The rows of the lock file at path ('-' is stdin)."""
    if path == "-":
        return parse(sys.stdin.buffer.read(), "<stdin>")
    with open(path, "rb") as f:
        return parse(f.read(), path)


def git(*args):
    r = subprocess.run(["git", *args], capture_output=True)
    return r.returncode, r.stdout


def history(lock, lpath, trusted):
    """Refusals: rows of trusted versions of lpath that lock lacks, and malformed trusted versions."""
    current = set(read(lock))
    rc, out = git("log", "--first-parent", "--diff-merges=first-parent", "--no-patch", "--format=%H",
                  trusted, "--", lpath)
    if rc != 0:
        return [f"lock: cannot list the trusted history of {lpath} through {trusted[:10]}"]
    refusals, reported = [], set()
    for c in out.decode().split():
        rc, blob = git("cat-file", "blob", f"{c}:{lpath}")
        if rc != 0:
            continue  # that commit deleted the lock; the lock it had is in an older version
        try:
            rows = parse(blob, f"{c[:10]}:{lpath}")
        except LockError as e:
            refusals += [f"lock: a trusted version is malformed: {p}" for p in e.problems]
            continue
        for row in rows:  # newest first, so the commit named is the newest that has the row
            if row not in current and row not in reported:
                reported.add(row)
                refusals.append(f"lock: '{row}' (in {c[:10]}, trusted history) is not in the lock: "
                                "recorded lines are only ever added, never rewritten or removed")
    return refusals


def main(argv):
    try:
        if len(argv) == 2 and argv[0] == "rows":
            for row in read(argv[1]):
                print(row)
            return 0
        if len(argv) == 4 and argv[0] == "history":
            refusals = history(*argv[1:])
            for r in refusals:
                print(r)
            return 1 if refusals else 0
    except LockError as e:
        print("\n".join(e.problems))
        return 1
    except OSError as e:
        print(f"legacy_lock.py: {e}", file=sys.stderr)
        return 2
    print("usage: legacy_lock.py rows FILE|- | history LOCK PATH TRUSTED", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
