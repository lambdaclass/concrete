#!/usr/bin/env bash
# Install the landing bot for user `dev` on the gate host. It does NOT enable the bot: it prints the
# enable command, because turning it on is the maintainers' decision.
#
#   install-bot.sh [--ssh dev@62.210.216.169] [--source-ref origin/main] [--clone ~/concrete-bot]
#
# --ssh runs this script on that host (key: CONCRETE_REMOTE_KEY, default ~/.ssh/concrete_ci).
# On the host it:
#   1. makes a DEDICATED clone (default ~/concrete-bot): the bot checks out trains there, so no human
#      or agent may work in it. Remotes: origin and lambdaclass; core.hooksPath=.githooks.
#   2. writes ~/.local/libexec/concrete-landing-bot, which fetches, extracts scripts/land from
#      <source-ref> into an immutable snapshot (keyed by commit) and runs the bot from there, so a
#      train checkout never rewrites the running script. Full gates run locally through
#      scripts/land/run-at-ref.sh, fetching the train SHA from the bot's clone.
#   3. writes ~/.config/concrete-landing-bot.env (kept if it exists) and the user units
#      concrete-landing-bot.{service,timer} from <source-ref>, then reloads systemd. Nothing is enabled.
set -euo pipefail
if [ "${1:-}" = --ssh ]; then
  host="${2:?--ssh needs user@host}"; shift 2
  exec ssh -i "${CONCRETE_REMOTE_KEY:-$HOME/.ssh/concrete_ci}" -o StrictHostKeyChecking=accept-new "$host" \
    bash -s -- "$@" < "$0"
fi
REF="origin/main"; CLONE="$HOME/concrete-bot"
while [ $# -gt 0 ]; do
  case "$1" in
    --source-ref) REF="$2"; shift ;;
    --clone) CLONE="$2"; shift ;;
    *) echo "install-bot: unknown argument $1" >&2; exit 2 ;;
  esac; shift
done
say() { echo "install-bot: $*"; }
[ "$(id -un)" = dev ] || say "WARNING: running as $(id -un), not dev"
ORIGIN_URL="${INSTALL_ORIGIN_URL:-$(git -C "$HOME/concrete2" remote get-url origin 2>/dev/null || echo git@github.com:unbalancedparentheses/concrete2.git)}"
MIRROR_URL="${INSTALL_MIRROR_URL:-git@github.com:lambdaclass/concrete.git}"

# 1. the dedicated clone
if [ ! -d "$CLONE/.git" ]; then
  say "cloning $ORIGIN_URL into $CLONE"
  git clone -q "$ORIGIN_URL" "$CLONE"
fi
cd "$CLONE"
git remote get-url lambdaclass >/dev/null 2>&1 || git remote add lambdaclass "$MIRROR_URL"
if git remote get-url fork >/dev/null 2>&1; then say "the clone has a remote named 'fork'; the bot refuses it, removing it"; git remote remove fork; fi
git config core.hooksPath .githooks
git config user.name >/dev/null || git config user.name "Concrete landing bot"
git config user.email >/dev/null || git config user.email "landing-bot@concrete-ci-1.invalid"
git fetch -q origin
git rev-parse --verify -q "$REF:scripts/land/bot.sh" >/dev/null \
  || { say "$REF has no scripts/land/bot.sh; pass --source-ref origin/wip/landing-bot until it lands"; exit 1; }
SHA="$(git rev-parse "$REF^{commit}")"

# 2. the launcher
mkdir -p "$HOME/.local/libexec" "$HOME/.local/state/concrete-landing-bot" "$HOME/.config/systemd/user"
cat > "$HOME/.local/libexec/concrete-landing-bot" <<EOF
#!/usr/bin/env bash
# Generated by scripts/land/install-bot.sh. Runs scripts/land/bot.sh from an immutable snapshot of
# \$BOT_SOURCE_REF, in the dedicated clone $CLONE.
set -euo pipefail
cd "$CLONE"
git fetch -q origin
sha="\$(git rev-parse --verify "\${BOT_SOURCE_REF:-$REF}^{commit}")"
snaps="\$HOME/.local/state/concrete-landing-bot/snap"
snap="\$snaps/\$sha"
if [ ! -f "\$snap/scripts/land/bot.sh" ]; then
  rm -rf "\$snap.tmp"; mkdir -p "\$snap.tmp"
  git archive "\$sha" scripts/land | tar -x -C "\$snap.tmp"
  mv "\$snap.tmp" "\$snap"
  ls -1t "\$snaps" | tail -n +6 | while read -r old; do rm -rf "\${snaps:?}/\$old"; done
fi
export LAND_REMOTE_RUNNER="\${LAND_REMOTE_RUNNER-\$snap/scripts/land/run-at-ref.sh}"
export RUN_AT_REF_SOURCE="\${RUN_AT_REF_SOURCE:-$CLONE}"
export LAND_REMOTE_PUSH="\${LAND_REMOTE_PUSH:-0}"
exec bash "\$snap/scripts/land/bot.sh" "\$@"
EOF
chmod 755 "$HOME/.local/libexec/concrete-landing-bot"

# 3. environment and units
ENVF="$HOME/.config/concrete-landing-bot.env"
if [ ! -f "$ENVF" ]; then
  cat > "$ENVF" <<EOF
# Landing bot environment (systemd EnvironmentFile; plain KEY=value lines).
BOT_SOURCE_REF=$REF
PATH=$HOME/.nix-profile/bin:/nix/var/nix/profiles/default/bin:/usr/local/bin:/usr/bin:/bin
LAND_REPO=unbalancedparentheses/concrete2
BOT_WATCH_INTERVAL=60
BOT_MAX_TRAINS=4
EOF
  say "wrote $ENVF"
else
  say "kept the existing $ENVF"
fi
for u in concrete-landing-bot.service concrete-landing-bot.timer; do
  git show "$SHA:scripts/land/systemd/$u" > "$HOME/.config/systemd/user/$u"
done
systemctl --user daemon-reload 2>/dev/null || say "systemctl --user daemon-reload failed (no user manager in this session); the enable command below reloads"

# Prerequisites the bot needs and this script does not create.
gh auth status >/dev/null 2>&1 && say "gh: authenticated" || say "MISSING: gh is not authenticated for $(id -un) (gh auth login); the bot dispatches and reads CI"
# ssh -T exits 1 even when it authenticates, so read its words, not its status.
gh_ssh="$(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new -T git@github.com 2>&1 || true)"
case "$gh_ssh" in
  *"successfully authenticated"*) say "github ssh: authenticated (it still needs WRITE access to both repositories)" ;;
  *) say "MISSING: no GitHub SSH identity for $(id -un); the bot pushes main to origin and lambdaclass, ci/* and notes to origin" ;;
esac

say "installed at $SHA ($REF); NOT enabled. To turn it on:"
echo "    sudo loginctl enable-linger dev        # once, as ubuntu: user timers run without a login"
echo "    systemctl --user daemon-reload && systemctl --user enable --now concrete-landing-bot.timer   # as dev"
echo "  pause: touch ~/.concrete-bot-paused   status: ~/.local/libexec/concrete-landing-bot status"
echo "  log:   ~/.local/state/concrete-landing-bot.log"
